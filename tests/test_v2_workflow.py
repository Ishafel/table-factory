def test_unsupported_mapping_has_context_and_prevents_all_outputs(
    tmp_path: Path,
    repository_config: Path,
) -> None:
    input_directory = tmp_path / "input"
    input_directory.mkdir()
    (input_directory / "01_valid.sql").write_text(
        "CREATE TABLE source_db.valid_table (id BIGINT);\n",
        encoding="utf-8",
    )
    (input_directory / "02_unsupported.sql").write_text(
        "CREATE TABLE source_db.unsupported_table (id BIGINT, payload ARRAY<STRING>);\n",
        encoding="utf-8",
    )
    output_directory = tmp_path / "output"

    generate_result = invoke_cli(
        "generate",
        "--input",
        input_directory,
        "--output",
        output_directory,
        "--config",
        repository_config,
        cwd=tmp_path,
        check=False,
    )

    assert generate_result.returncode == 2
    for context in (
        "source_db.unsupported_table",
        "payload",
        "ARRAY<STRING>",
        "no lossless scalar mapping",
    ):
        assert context in generate_result.stderr
    assert not output_directory.exists()

    validate_result = invoke_cli(
        "validate",
        "--input",
        input_directory,
        "--config",
        repository_config,
        cwd=tmp_path,
        check=False,
    )
    assert validate_result.returncode == 2
    assert "source_db.unsupported_table" in validate_result.stderr
    assert "payload" in validate_result.stderr
    assert "ARRAY<STRING>" in validate_result.stderr
    assert not list(tmp_path.rglob("*.tmp"))


