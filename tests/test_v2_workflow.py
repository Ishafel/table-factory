FIXTURES = Path(__file__).parent / "fixtures"
LARGE_DDL = FIXTURES / "large_show_create.sql"
COMMENTS_DDL = FIXTURES / "comments_and_partitions.sql"

ARTIFACT_ROLES = (
    "01_hive_create_physical",
    "02_hive_insert",
    "03_greenplum_create_external",
    "04_greenplum_create_physical",
    "05_greenplum_insert",
)

EXPECTED_LARGE_COLUMN_NAMES = tuple(f"column_{index:03d}" for index in range(1, 112))

LARGE_GREENPLUM_TYPES = {
    "STRING": "TEXT",
    "TIMESTAMP": "TIMESTAMP",
    "BIGINT": "BIGINT",
    "DECIMAL(38,12)": "NUMERIC(38,12)",
    "DECIMAL(38,0)": "NUMERIC(38,0)",
}


def _artifact_names(stem: str) -> tuple[str, ...]:
    return tuple(f"{stem}__{role}.sql" for role in ARTIFACT_ROLES)


def _read_artifacts(output_directory: Path) -> dict[str, str]:
    return {
        path.name: path.read_text(encoding="utf-8")
        for path in sorted(output_directory.glob("*.sql"))
        if path.is_file()
    }


def _generate(
    ddl: Path,
    output_directory: Path,
    *,
    repository_config: Path,
    cwd: Path,
) -> dict[str, str]:
    invoke_cli(
        "generate",
        "--input",
        ddl,
        "--output",
        output_directory,
        "--config",
        repository_config,
        cwd=cwd,
    )
    return _read_artifacts(output_directory)


def _normalized_type(data_type: str) -> str:
    return re.sub(r"\s+", "", data_type).upper()


def _modified_config(
    repository_config: Path,
    destination: Path,
    *replacements: tuple[str, str],
) -> Path:
    contents = repository_config.read_text(encoding="utf-8")
    for old, new in replacements:
        assert old in contents
        contents = contents.replace(old, new, 1)
    destination.write_text(contents, encoding="utf-8")
    return destination


def _hive_identifier_block(column_names: tuple[str, ...]) -> str:
    return ",\n".join(f"  `{name}`" for name in column_names)


def _greenplum_identifier_block(column_names: tuple[str, ...]) -> str:
    return ",\n".join(f'  "{name}"' for name in column_names)


def test_large_show_create_fixture_preserves_all_111_columns() -> None:
    ddl = LARGE_DDL.read_text(encoding="utf-8")
    tables = parse_hive_ddl(ddl)

    assert not ddl.rstrip().endswith(";")
    assert len(tables) == 1

    table = tables[0]
    assert table.database == "sample_source"
    assert table.name == "large_table"
    assert table.qualified_name == "sample_source.large_table"
    assert table.external is False
    assert table.create_sql == ddl.strip()
    assert table.partition_columns == ()
    assert table.comment is None

    assert len(table.columns) == 111
    assert tuple(column.name for column in table.columns) == EXPECTED_LARGE_COLUMN_NAMES
    assert all(column.comment is None for column in table.columns)
    assert Counter(_normalized_type(column.data_type) for column in table.columns) == {
        "STRING": 85,
        "TIMESTAMP": 22,
        "BIGINT": 1,
        "DECIMAL(38,12)": 2,
        "DECIMAL(38,0)": 1,
    }
    assert {
        column.name: _normalized_type(column.data_type)
        for column in table.columns
        if column.name in {"column_022", "column_088", "column_110", "column_111"}
    } == {
        "column_022": "DECIMAL(38,12)",
        "column_088": "DECIMAL(38,12)",
        "column_110": "BIGINT",
        "column_111": "DECIMAL(38,0)",
    }

    # The split Spark schema is deliberately present, but is not a schema source.
    assert "'spark.sql.sources.schema.numParts'='2'" in ddl
    assert "'spark.sql.sources.schema.part.0'=" in ddl
    assert "'spark.sql.sources.schema.part.1'=" in ddl
    assert "nullable" not in EXPECTED_LARGE_COLUMN_NAMES


def test_large_fixture_generates_exact_five_role_chain_deterministically(
    tmp_path: Path,
    repository_config: Path,
) -> None:
    output_directory = tmp_path / "generated"
    generated = _generate(
        LARGE_DDL,
        output_directory,
        repository_config=repository_config,
        cwd=tmp_path,
    )
    expected_names = _artifact_names("sample_source_large_table")

    assert tuple(generated) == expected_names
    assert all(
        generated[name].startswith("-- Generated by table-factory") for name in expected_names
    )

    table = parse_hive_ddl(LARGE_DDL.read_text(encoding="utf-8"))[0]
    column_names = tuple(column.name for column in table.columns)
    hive_definitions = ",\n".join(
        f"  `{column.name}` {column.data_type}" for column in table.columns
    )
    greenplum_definitions = ",\n".join(
        f'  "{column.name}" {LARGE_GREENPLUM_TYPES[_normalized_type(column.data_type)]}'
        for column in table.columns
    )
    hive_identifiers = _hive_identifier_block(column_names)
    greenplum_identifiers = _greenplum_identifier_block(column_names)

    hive_create = generated[expected_names[0]]
    assert (
        f"CREATE TABLE `target_hive_db`.`large_table_physical` (\n{hive_definitions}\n)"
    ) in hive_create
    assert "ROW FORMAT DELIMITED" in hive_create
    assert "FIELDS TERMINATED BY ','" in hive_create
    assert "ESCAPED BY '\\\\'" in hive_create
    assert "NULL DEFINED AS '\\\\N'" in hive_create
    assert "STORED AS TEXTFILE;" in hive_create
    for source_only_fragment in (
        "CREATE EXTERNAL TABLE",
        "PARTITIONED BY",
        "LOCATION",
        "ParquetHiveSerDe",
        "MapredParquetInputFormat",
        "MapredParquetOutputFormat",
        "TBLPROPERTIES",
        "spark.sql.",
        "hdfs://",
    ):
        assert source_only_fragment not in hive_create

    hive_insert = generated[expected_names[1]]
    assert (
        "INSERT INTO TABLE `target_hive_db`.`large_table_physical` "
        f"(\n{hive_identifiers}\n)\n"
        f"SELECT\n{hive_identifiers}\n"
        "FROM `sample_source`.`large_table`;"
    ) in hive_insert

    greenplum_external = generated[expected_names[2]]
    assert (
        f'CREATE EXTERNAL TABLE "ext"."large_table_ext" (\n{greenplum_definitions}\n)'
    ) in greenplum_external
    assert (
        "LOCATION (\n"
        "  'pxf://target_hive_db.large_table_physical?PROFILE=hive&SERVER=default'\n"
        ") ON ALL\n"
        "FORMAT 'CUSTOM' (FORMATTER='pxfwritable_import')\n"
        "ENCODING 'UTF8';"
    ) in greenplum_external
    assert "sample_source" not in greenplum_external
    assert "target_gp_database" not in greenplum_external

    greenplum_create = generated[expected_names[3]]
    assert (
        f'CREATE TABLE "dwh"."large_table" (\n{greenplum_definitions}\n)\nDISTRIBUTED RANDOMLY;'
    ) in greenplum_create
    assert "CREATE EXTERNAL TABLE" not in greenplum_create
    assert "PARTITIONED BY" not in greenplum_create
    assert "target_gp_database" not in greenplum_create

    greenplum_insert = generated[expected_names[4]]
    assert (
        'INSERT INTO "dwh"."large_table" '
        f"(\n{greenplum_identifiers}\n)\n"
        f"SELECT\n{greenplum_identifiers}\n"
        'FROM "ext"."large_table_ext";'
    ) in greenplum_insert

    all_sql = "\n".join(generated.values())
    assert "SELECT *" not in all_sql.upper()
    for legacy_command in (
        r"\bDROP\b",
        r"\bDESCRIBE\b",
        r"\bSHOW\s+CREATE\b",
        r"\bANALYZE\b",
        r"\bTRUNCATE\b",
    ):
        assert re.search(legacy_command, all_sql, flags=re.IGNORECASE) is None

    first_bytes = {name: (output_directory / name).read_bytes() for name in expected_names}
    regenerated = _generate(
        LARGE_DDL,
        output_directory,
        repository_config=repository_config,
        cwd=tmp_path,
    )
    second_bytes = {name: (output_directory / name).read_bytes() for name in expected_names}
    assert tuple(regenerated) == expected_names
    assert second_bytes == first_bytes
    assert not list(output_directory.glob("*.tmp"))


def test_comments_and_partition_columns_are_flattened_and_escaped(
    tmp_path: Path,
    repository_config: Path,
) -> None:
    table = parse_hive_ddl(COMMENTS_DDL.read_text(encoding="utf-8"))[0]

    assert table.external is True
    assert table.qualified_name == "source_db.events"
    assert table.comment == "События команды O'Brien"
    assert [(column.name, column.comment) for column in table.columns] == [
        ("event_id", "Идентификатор"),
        ("owner", "O'Brien"),
        ("amount", None),
    ]
    assert [(column.name, column.comment) for column in table.partition_columns] == [
        ("event_day", "День события")
    ]
    ordered_names = ("event_id", "owner", "amount", "event_day")
    assert tuple(column.name for column in table.all_columns) == ordered_names

    generated = _generate(
        COMMENTS_DDL,
        tmp_path / "comments output",
        repository_config=repository_config,
        cwd=tmp_path,
    )
    expected_names = _artifact_names("source_db_events")
    assert tuple(generated) == expected_names

    hive_create = generated[expected_names[0]]
    assert "CREATE TABLE `target_hive_db`.`events_physical`" in hive_create
    assert "`event_id` BIGINT COMMENT 'Идентификатор'" in hive_create
    assert "`owner` STRING COMMENT 'O\\'Brien'" in hive_create
    assert "`amount` DECIMAL(18, 2)" in hive_create
    assert "`event_day` DATE COMMENT 'День события'" in hive_create
    assert "COMMENT 'События команды O\\'Brien'" in hive_create
    assert "CREATE EXTERNAL TABLE" not in hive_create
    assert "PARTITIONED BY" not in hive_create
    assert "STORED AS PARQUET" not in hive_create
    assert "STORED AS TEXTFILE" in hive_create
    assert hive_create.index("`amount`") < hive_create.index("`event_day`")

    hive_identifiers = _hive_identifier_block(ordered_names)
    hive_insert = generated[expected_names[1]]
    assert (
        f"(\n{hive_identifiers}\n)\nSELECT\n{hive_identifiers}\nFROM `source_db`.`events`;"
    ) in hive_insert

    greenplum_identifiers = _greenplum_identifier_block(ordered_names)
    greenplum_external = generated[expected_names[2]]
    greenplum_create = generated[expected_names[3]]
    greenplum_insert = generated[expected_names[4]]
    for create_sql in (greenplum_external, greenplum_create):
        assert '"event_id" BIGINT' in create_sql
        assert '"owner" TEXT' in create_sql
        assert '"amount" NUMERIC(18,2)' in create_sql
        assert '"event_day" DATE' in create_sql
        assert create_sql.index('"amount"') < create_sql.index('"event_day"')
        assert "PARTITIONED BY" not in create_sql
        assert "O\\'Brien" not in create_sql
        assert "'События команды O''Brien'" in create_sql
        assert "'O''Brien'" in create_sql
        assert "'Идентификатор'" in create_sql
        assert "'День события'" in create_sql

    assert (
        "COMMENT ON TABLE \"ext\".\"events_ext\" IS 'События команды O''Brien';"
    ) in greenplum_external
    assert (
        'COMMENT ON COLUMN "ext"."events_ext"."event_day" IS \'День события\';'
    ) in greenplum_external
    assert (
        "COMMENT ON TABLE \"dwh\".\"events\" IS 'События команды O''Brien';"
    ) in greenplum_create
    assert ('COMMENT ON COLUMN "dwh"."events"."event_day" IS \'День события\';') in greenplum_create
    assert (
        "pxf://target_hive_db.events_physical?PROFILE=hive&SERVER=default"
    ) in greenplum_external
    assert (
        f'(\n{greenplum_identifiers}\n)\nSELECT\n{greenplum_identifiers}\nFROM "ext"."events_ext";'
    ) in greenplum_insert
    assert "SELECT *" not in hive_insert.upper()
    assert "SELECT *" not in greenplum_insert.upper()


