def test_hive_source_target_overlap_uses_unicode_normalization(
    tmp_path: Path,
    repository_config: Path,
) -> None:
    ddl = tmp_path / "unicode_source_target_collision.sql"
    decomposed_source_name = "Cafe\u0301"
    composed_target_name = "Café"
    ddl.write_text(
        f"CREATE TABLE target_hive_db.`{decomposed_source_name}` (id BIGINT);\n"
        f"CREATE TABLE `{composed_target_name}`.events (id BIGINT);\n",
        encoding="utf-8",
    )
    config = _modified_config(
        repository_config,
        tmp_path / "unicode_collision.yaml",
        (
            'physical_table_name_template: "{source_table}_physical"',
            'physical_table_name_template: "{source_database}"',
        ),
        (
            'external_table_name_template: "{source_table}_ext"',
            'external_table_name_template: "{source_database}_ext"',
        ),
        (
            'physical_table_name_template: "{source_table}"',
            'physical_table_name_template: "{source_database}"',
        ),
    )
    output_directory = tmp_path / "output"

    result = invoke_cli(
        "generate",
        "--input",
        ddl,
        "--output",
        output_directory,
        "--config",
        config,
        cwd=tmp_path,
        check=False,
    )

    assert result.returncode == 2
    assert f"generated Hive target target_hive_db.{composed_target_name}" in result.stderr
    assert f"source Hive table target_hive_db.{decomposed_source_name}" in result.stderr
    assert "in the input batch" in result.stderr
    assert not output_directory.exists()


