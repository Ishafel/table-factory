_MAX_STEM_BYTES = 160


@dataclass(frozen=True, slots=True)
class Artifact:
    """One pending output file."""

    filename: str
    content: str


@dataclass(slots=True)
class _ArtifactWriteState:
    """Preallocated transaction state for one destination."""

    artifact: Artifact
    destination_name: str
    temporary_name: str | None = None
    backup_name: str | None = None
    backup_started: bool = False
    backup_completed: bool = False
    commit_started: bool = False
    commit_completed: bool = False


def _safe_stem(table: Table) -> str:
    raw = table.qualified_name
    normalized = unicodedata.normalize("NFKC", raw)
    characters = [
        character if character.isalnum() or character in {"_", "-"} else "_"
        for character in normalized
    ]
    stem = re.sub(r"_+", "_", "".join(characters)).strip("._-")
    if not stem or stem in {".", ".."}:
        stem = "table"
    result: list[str] = []
    byte_count = 0
    for character in stem:
        encoded_length = len(character.encode("utf-8"))
        if byte_count + encoded_length > _MAX_STEM_BYTES:
            break
        result.append(character)
        byte_count += encoded_length
    return "".join(result) or "table"


def _safe_comment_text(value: str) -> str:
    return "".join(
        character if character.isprintable() and character not in "\r\n" else "_"
        for character in value
    )


def artifact_filenames(
    table: Table | TablePlan,
    *,
    config: FactoryConfig,
) -> tuple[str, ...]:
    """Return every potential output name without invoking a renderer."""
    source = table.source if isinstance(table, TablePlan) else table
    stem = _safe_stem(source)
    separator = config.filename_separator
    return tuple(f"{stem}{separator}{role}.sql" for role in ARTIFACT_ROLES)


def iter_artifacts(
    table: Table | TablePlan,
    *,
    config: FactoryConfig,
    source_label: str,
) -> Iterator[Artifact]:
    """Render enabled artifacts one at a time in deterministic role order."""
    plan = (
        table
        if isinstance(table, TablePlan)
        else TablePlan(
            source_label=source_label,
            source=table,
            targets=build_target_names(table, config),
            mapped_columns=map_table_columns(table),
        )
    )
    label_basename = source_label.replace("\\", "/").rsplit("/", maxsplit=1)[-1]
    safe_source_label = _safe_comment_text(label_basename)
    header = (
        f"-- Generated by table-factory from {safe_source_label}\n"
        if config.include_source_comment
        else ""
    )

    def liquibase_content() -> str:
        statement = render_greenplum_create_external_liquibase(plan, config=config)
        marker, newline, remainder = statement.partition("\n")
        if marker != "--liquibase formatted sql" or not newline:
            raise AssertionError("Liquibase renderer omitted its required first line")
        return f"{marker}\n{header}{remainder}"

    renderers: tuple[Callable[[], str], ...] = (
        lambda: header + render_hive_create_physical(plan, config=config),
        lambda: header + render_hive_insert(plan, config=config),
        lambda: header + render_greenplum_create_external(plan, config=config),
        liquibase_content,
        lambda: header + render_greenplum_create_physical(plan, config=config),
        lambda: header + render_greenplum_insert(plan),
    )
    filenames = artifact_filenames(plan, config=config)
    for role, filename, renderer in zip(
        ARTIFACT_ROLES,
        filenames,
        renderers,
        strict=True,
    ):
        if config.output.artifact_enabled(role):
            yield Artifact(
                filename=filename,
                content=renderer(),
            )


def render_artifacts(
    table: Table | TablePlan,
    *,
    config: FactoryConfig,
    source_label: str,
) -> tuple[Artifact, ...]:
    """Render the configured subset of workflow and Liquibase artifacts."""
    return tuple(
        iter_artifacts(
            table,
            config=config,
            source_label=source_label,
        )
    )


def ensure_unique_artifact_names(filenames: Iterable[str]) -> None:
    """Reject potential outputs that collide after safe-name normalization."""
    names: set[str] = set()
    duplicates: set[str] = set()
    for filename in filenames:
        comparison_name = unicodedata.normalize("NFKC", filename).casefold()
        if comparison_name in names:
            duplicates.add(filename)
        names.add(comparison_name)
    if duplicates:
        duplicate_list = ", ".join(sorted(duplicates))
        raise TableFactoryError(f"multiple tables map to the same output name: {duplicate_list}")


def ensure_unique_artifacts(artifacts: list[Artifact]) -> None:
    """Reject rendered outputs that would overwrite each other."""
    ensure_unique_artifact_names(artifact.filename for artifact in artifacts)


def _destination_name(filename: str) -> str:
    if not filename or filename in {".", ".."} or Path(filename).name != filename:
        raise OutputSafetyError("generated filename is not a plain filename")
    try:
        os.fsencode(filename)
    except UnicodeEncodeError:
        raise OutputSafetyError(
            "generated filename cannot be represented by the process filesystem encoding; "
            "UTF-8 is required"
        ) from None
    return filename


def _unlink_error(directory_fd: int, name: str) -> OSError | None:
    try:
        os.unlink(name, dir_fd=directory_fd)
    except FileNotFoundError:
        return None
    except OSError as error:
        return error
    return None


def _write_staged_file(
    output_directory_fd: int,
    artifact: Artifact,
) -> str:
    descriptor: int | None = None
    temporary_name: str | None = None
    try:
        descriptor, temporary_name = _open_exclusive_file(
            output_directory_fd,
            prefix=f".{artifact.filename}.",
            suffix=".tmp",
        )
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            descriptor = None
            handle.write(artifact.content)
            handle.flush()
            os.fsync(handle.fileno())
        return temporary_name
    except MemoryError:
        if descriptor is not None:
            with suppress(OSError, MemoryError):
                os.close(descriptor)
        if temporary_name is not None:
            with suppress(OSError, MemoryError):
                os.unlink(temporary_name, dir_fd=output_directory_fd)
        raise
    except OSError as error:
        if descriptor is not None:
            with suppress(OSError):
                os.close(descriptor)
        cleanup_error = (
            _unlink_error(output_directory_fd, temporary_name)
            if temporary_name is not None
            else None
        )
        detail = error.strerror or "I/O error"
        if cleanup_error is not None:
            cleanup_detail = cleanup_error.strerror or "I/O error"
            detail = f"{detail}; temporary-file cleanup failed: {cleanup_detail}"
        raise OutputSafetyError(
            f"cannot stage generated file {artifact.filename}: {detail}"
        ) from None


def _open_exclusive_file(
    directory_fd: int,
    *,
    prefix: str,
    suffix: str,
) -> tuple[int, str]:
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0)
    for _attempt in range(100):
        name = f"{prefix}{secrets.token_hex(8)}{suffix}"
        try:
            descriptor = os.open(name, flags, 0o600, dir_fd=directory_fd)
        except FileExistsError:
            continue
        try:
            result = (descriptor, name)
        except MemoryError:
            with suppress(OSError, MemoryError):
                os.close(descriptor)
            with suppress(OSError, MemoryError):
                os.unlink(name, dir_fd=directory_fd)
            raise
        return result
    raise FileExistsError("cannot allocate a unique transaction filename")


def _reserved_backup_name(output_directory_fd: int, filename: str) -> str:
    descriptor, backup_name = _open_exclusive_file(
        output_directory_fd,
        prefix=f".{filename}.",
        suffix=".bak",
    )
    try:
        os.close(descriptor)
    except (OSError, MemoryError):
        with suppress(OSError, MemoryError):
            os.unlink(backup_name, dir_fd=output_directory_fd)
        raise
    return backup_name


def _input_file_identities(
    input_paths: tuple[Path, ...],
    verified_identities: tuple[FileIdentity, ...],
) -> frozenset[FileIdentity]:
    identities = set(verified_identities)
    for input_path in input_paths:
        descriptor: int | None = None
        try:
            descriptor, status = open_pinned_path(input_path, create_directory=False)
            if not stat.S_ISREG(status.st_mode):
                raise OSError("input path is not a regular file")
            identities.add(FileIdentity.from_stat(status))
        except (OSError, PathSafetyError) as error:
            detail = getattr(error, "strerror", None) or str(error) or "I/O error"
            raise OutputSafetyError(
                f"cannot verify an input SQL file before writing output: {detail}"
            ) from None
        finally:
            if descriptor is not None:
                with suppress(OSError):
                    os.close(descriptor)
    return frozenset(identities)


def _reject_input_aliases(
    output_directory_fd: int,
    destinations: list[tuple[Artifact, str]],
    input_identities: frozenset[FileIdentity],
) -> None:
    """Reject any destination that names the same file as a source DDL."""
    for artifact, destination_name in destinations:
        try:
            status = os.stat(
                destination_name,
                dir_fd=output_directory_fd,
                follow_symlinks=True,
            )
        except FileNotFoundError:
            continue
        except OSError as error:
            detail = error.strerror or "I/O error"
            raise OutputSafetyError(
                "cannot verify whether generated file "
                f"{artifact.filename} aliases an input SQL file: {detail}"
            ) from None
        if FileIdentity.from_stat(status) in input_identities:
            raise OutputSafetyError(
                "refusing to overwrite an input SQL file with generated artifact "
                f"{artifact.filename}"
            )


def _replace_in_directory(directory_fd: int, source: str, destination: str) -> None:
    os.replace(
        source,
        destination,
        src_dir_fd=directory_fd,
        dst_dir_fd=directory_fd,
    )


def _destination_exists(output_directory_fd: int, name: str) -> bool:
    try:
        os.stat(name, dir_fd=output_directory_fd, follow_symlinks=False)
    except FileNotFoundError:
        return False
    return True


def _rollback_artifact_transaction(
    output_directory_fd: int,
    states: list[_ArtifactWriteState],
) -> OSError | None:
    """Restore the pre-transaction set after a regular filesystem failure."""
    rollback_error: OSError | None = None
    for state in reversed(states):
        committed = state.commit_completed
        if state.commit_started and not committed and state.temporary_name is not None:
            try:
                committed = not _destination_exists(
                    output_directory_fd,
                    state.temporary_name,
                )
            except OSError as error:
                rollback_error = rollback_error or error
        if not committed:
            continue
        try:
            os.unlink(state.destination_name, dir_fd=output_directory_fd)
        except FileNotFoundError:
            pass
        except OSError as error:
            rollback_error = rollback_error or error
        else:
            state.commit_started = False
            state.commit_completed = False

    for state in reversed(states):
        backup_name = state.backup_name
        if backup_name is None:
            continue
        restore_backup = state.backup_completed
        discard_reservation = not state.backup_started
        if state.backup_started and not state.backup_completed:
            try:
                destination_exists = _destination_exists(
                    output_directory_fd,
                    state.destination_name,
                )
            except OSError as error:
                rollback_error = rollback_error or error
            else:
                restore_backup = not destination_exists
                discard_reservation = destination_exists

        if restore_backup:
            try:
                _replace_in_directory(
                    output_directory_fd,
                    backup_name,
                    state.destination_name,
                )
            except OSError as error:
                rollback_error = rollback_error or error
            else:
                state.backup_name = None
                state.backup_started = False
                state.backup_completed = False
                state.commit_started = False
                state.commit_completed = False
        elif discard_reservation:
            unlink_error = _unlink_error(output_directory_fd, backup_name)
            if unlink_error is None:
                state.backup_name = None
                state.backup_started = False
            else:
                rollback_error = rollback_error or unlink_error
    return rollback_error


def _best_effort_path_exists(directory_fd: int, name: str) -> bool | None:
    try:
        return _destination_exists(directory_fd, name)
    except Exception:
        return None


def _best_effort_unlink(directory_fd: int, name: str) -> None:
    with suppress(Exception):
        os.unlink(name, dir_fd=directory_fd)


def _recover_artifact_transaction_after_memory_error(
    output_directory_fd: int,
    states: list[_ArtifactWriteState],
    *,
    completed: bool,
) -> None:
    """Allocation-light recovery that must never replace the original MemoryError."""
    if not completed:
        index = len(states) - 1
        while index >= 0:
            state = states[index]
            committed = state.commit_completed
            if state.commit_started and not committed and state.temporary_name is not None:
                temporary_exists = _best_effort_path_exists(
                    output_directory_fd,
                    state.temporary_name,
                )
                committed = temporary_exists is False
            if committed:
                _best_effort_unlink(output_directory_fd, state.destination_name)
                state.commit_started = False
                state.commit_completed = False
            index -= 1

        index = len(states) - 1
        while index >= 0:
            state = states[index]
            backup_name = state.backup_name
            if backup_name is not None:
                restore_backup = state.backup_completed
                discard_reservation = not state.backup_started
                if state.backup_started and not state.backup_completed:
                    destination_exists = _best_effort_path_exists(
                        output_directory_fd,
                        state.destination_name,
                    )
                    restore_backup = destination_exists is False
                    discard_reservation = destination_exists is True
                if restore_backup:
                    with suppress(Exception):
                        _replace_in_directory(
                            output_directory_fd,
                            backup_name,
                            state.destination_name,
                        )
                elif discard_reservation:
                    _best_effort_unlink(output_directory_fd, backup_name)
            index -= 1

    for state in states:
        if state.temporary_name is not None:
            _best_effort_unlink(output_directory_fd, state.temporary_name)
        if completed and state.backup_name is not None:
            _best_effort_unlink(output_directory_fd, state.backup_name)


def write_artifacts(
    output_directory: Path,
    artifacts: list[Artifact],
    *,
    input_paths: tuple[Path, ...] = (),
    input_identities: tuple[FileIdentity, ...] = (),
) -> None:
    """Replace the complete artifact set with rollback on any write failure."""
    destinations: list[tuple[Artifact, str]] = []
    for artifact in artifacts:
        destinations.append((artifact, _destination_name(artifact.filename)))
    states = [
        _ArtifactWriteState(
            artifact=artifact,
            destination_name=destination_name,
        )
        for artifact, destination_name in destinations
    ]
    verified_input_identities = _input_file_identities(input_paths, input_identities)

    output_directory_fd: int | None = None
    try:
        output_directory_fd, _output_status = open_pinned_path(
            output_directory,
            create_directory=True,
        )
    except UntrustedSymlinkError:
        raise OutputSafetyError("output path must not contain a symbolic-link component") from None
    except PathIdentityChangedError:
        raise OutputSafetyError("output path changed while it was being opened") from None
    except SecurePathUnsupportedError as error:
        raise OutputSafetyError(f"cannot safely open output directory: {error}") from None
    except NotADirectoryError:
        raise OutputSafetyError("output path is not a directory") from None
    except OSError as error:
        detail = error.strerror or "I/O error"
        raise OutputSafetyError(f"cannot create output directory: {detail}") from None

    try:
        for artifact, destination_name in destinations:
            try:
                destination_status = os.stat(
                    destination_name,
                    dir_fd=output_directory_fd,
                    follow_symlinks=False,
                )
            except FileNotFoundError:
                continue
            except OSError as error:
                detail = error.strerror or "I/O error"
                raise OutputSafetyError(
                    f"cannot inspect generated file {artifact.filename}: {detail}"
                ) from None
            if stat.S_ISDIR(destination_status.st_mode):
                raise OutputSafetyError(
                    f"cannot write generated file {artifact.filename}: destination is a directory"
                )
        _reject_input_aliases(
            output_directory_fd,
            destinations,
            verified_input_identities,
        )

        current_filename = "artifact set"
        completed = False
        failure: OutputSafetyError | None = None
        try:
            try:
                for state in states:
                    current_filename = state.artifact.filename
                    state.temporary_name = _write_staged_file(
                        output_directory_fd,
                        state.artifact,
                    )

                for state in states:
                    if not _destination_exists(
                        output_directory_fd,
                        state.destination_name,
                    ):
                        continue
                    current_filename = state.artifact.filename
                    backup_name = _reserved_backup_name(
                        output_directory_fd,
                        state.artifact.filename,
                    )
                    state.backup_name = backup_name
                    state.backup_started = True
                    _replace_in_directory(
                        output_directory_fd,
                        state.destination_name,
                        backup_name,
                    )
                    state.backup_completed = True

                for state in states:
                    if state.temporary_name is None:
                        raise AssertionError("artifact staging omitted its temporary file")
                    current_filename = state.artifact.filename
                    state.commit_started = True
                    _replace_in_directory(
                        output_directory_fd,
                        state.temporary_name,
                        state.destination_name,
                    )
                    state.commit_completed = True
                completed = True
            except (OSError, OutputSafetyError) as error:
                rollback_error = _rollback_artifact_transaction(
                    output_directory_fd,
                    states,
                )
                if isinstance(error, OutputSafetyError):
                    detail = str(error)
                else:
                    detail = error.strerror or "I/O error"
                if rollback_error is not None:
                    rollback_detail = rollback_error.strerror or "I/O error"
                    detail = f"{detail}; rollback failed: {rollback_detail}"
                failure = OutputSafetyError(
                    f"cannot write generated file {current_filename}: {detail}"
                )

            cleanup_failures: list[str] = []
            for state in states:
                if state.temporary_name is None:
                    continue
                unlink_failure = _unlink_error(output_directory_fd, state.temporary_name)
                if unlink_failure is not None:
                    cleanup_detail = unlink_failure.strerror or "I/O error"
                    cleanup_failures.append(f"{state.artifact.filename}: {cleanup_detail}")
                else:
                    state.temporary_name = None
            if completed:
                for state in states:
                    if state.backup_name is None:
                        continue
                    unlink_failure = _unlink_error(output_directory_fd, state.backup_name)
                    if unlink_failure is not None:
                        cleanup_detail = unlink_failure.strerror or "I/O error"
                        cleanup_failures.append(f"{state.destination_name}: {cleanup_detail}")
                    else:
                        state.backup_name = None
                        state.backup_started = False
                        state.backup_completed = False

            if cleanup_failures:
                cleanup_detail = "; ".join(cleanup_failures)
                if failure is None:
                    failure = OutputSafetyError(
                        "generated files were replaced, but transaction cleanup failed: "
                        f"{cleanup_detail}"
                    )
                else:
                    failure = OutputSafetyError(f"{failure}; cleanup failed: {cleanup_detail}")
            if failure is not None:
                raise failure from None
        except MemoryError:
            with suppress(Exception):
                _recover_artifact_transaction_after_memory_error(
                    output_directory_fd,
                    states,
                    completed=completed,
                )
            raise
    finally:
        os.close(output_directory_fd)
